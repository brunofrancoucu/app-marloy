import type { Metadata } from 'next'
import { Plus_Jakarta_Sans, Inter } from 'next/font/google'
import '@/styles/globals.css'

import Navbar from './(layout)/components/Navbar'
import Footer from './(layout)/components/Footer'

import { Locale } from '@/lib/services/language/server'

const jakarta = Plus_Jakarta_Sans({
  subsets: ['latin'],
  variable: '--font-primary',
})

// Secondary Font for Body/UI
const inter = Inter({
  subsets: ['latin'],
  variable: '--font-secondary',
})

export const metadata: Metadata = {
  title: 'Create Next App',
  description: 'Generated by create next app',
}

// This tells Next.js to statically generate these three paths at build time!
export async function generateStaticParams() {
  return [{ lang: 'en' }, { lang: 'ru' }, { lang: 'es' }]
}

// `modal` auto maps to @modal folder
export default async function RootLayout({
  children,
  modal,
  params, // From [lang] folder
}: {
  children: React.ReactNode
  modal: React.ReactNode
  params: Promise<{ lang: Locale }>
}) {
  const lang = (await params).lang

  // This raw JavaScript runs before the browser paints.
  // It reads the cookie directly on the client side.
  const themeScript = `
    (function() {
      try {
        // 1. Function to read the current expected theme
        function getTheme() {
          var match = document.cookie.match(new RegExp('(^| )theme=([^;]+)'));
          var theme = match ? match[2] : null;
          if (!theme) {
            theme = window.matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light';
          }
          return theme;
        }

        // 2. Function to safely apply the theme
        function applyTheme() {
          var theme = getTheme();
          console.log("Observed changes")
          var isDark = document.documentElement.classList.contains('dark');
          
          if (theme === 'dark' && !isDark) {
            document.documentElement.classList.add('dark');
          } else if (theme !== 'dark' && isDark) {
            document.documentElement.classList.remove('dark');
          }
        }

        // 3. Apply theme instantly on initial page load
        applyTheme();

        // 4. Protect the class! If React strips the class during a language 
        // route change, this observer instantly puts it back.
        new MutationObserver(function() {
          applyTheme();
        }).observe(document.documentElement, { attributes: true, attributeFilter: ['class'] });

      } catch (e) {}
    })();
  `

  return (
    <html
      lang={lang}
      className={`${inter.variable} ${jakarta.variable}`}
      suppressHydrationWarning
    >
      <head>
        {/* Render blocking script */}
        <script dangerouslySetInnerHTML={{ __html: themeScript }} />
      </head>
      <body className={`flex min-h-screen flex-col font-sans antialiased`}>
        <Navbar lang={lang} />
        <main className="flex-grow">{children}</main>
        {modal} {/* The modal renders here when active */}
        <Footer lang={lang} />
      </body>
    </html>
  )
}
